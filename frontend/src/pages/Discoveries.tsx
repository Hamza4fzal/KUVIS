import { useState } from "react";
import { useNavigate } from "react-router-dom";
import { useDiscoveries } from "@/services/api";
import { useMapStore } from "@/store/mapStore";
import { Empty, ErrorState, EvidenceChip, Loading, PageHeader } from "@/components/ui";
import { fmt } from "@/maps/palettes";

const KIND: Record<string, string> = {
  "Spatial heat concentration": "cluster", "Thermal profile": "cluster", "Environmental association": "association",
  "Unusual heat observation": "anomaly", "Vegetation change": "derived", "Urban transformation": "derived",
  "Overlapping environmental stress": "composite", "Statistical relationship": "statistic", "Historical change": "derived",
  "Flood-related profile": "cluster", "Unusual change": "anomaly", "Infrastructure profile": "cluster", "Rainfall": "assigned",
};

export default function Discoveries() {
  const [cat, setCat] = useState<string | undefined>();
  const { data, isLoading, error } = useDiscoveries();
  const nav = useNavigate();
  const { setFlyTo, select } = useMapStore();
  if (isLoading) return <Loading label="Loading discoveries" />;
  if (error) return <div className="p-6"><ErrorState error={error} /></div>;
  const items = data?.items ?? [];
  const cats = Array.from(new Set(items.map((d) => d.category)));
  const shown = cat ? items.filter((d) => d.category === cat) : items;
  return (
    <div className="h-full overflow-y-auto scroll-thin">
      <div className="max-w-[1200px] mx-auto p-6">
        <PageHeader kicker="Discovered patterns" title="What the data-mining experiments found">
          Each discovery below is generated by code from stored experiment outputs and passes a quality threshold (minimum size, statistical
          support or effect size). The wording is templated from the numbers; nothing here is hand-written. Ranked by strength — a
          normalized measure of each discovery's effect, defined per category in the evidence block.
        </PageHeader>
        <div className="flex flex-wrap gap-1.5 mb-4">
          <button className={`chip ${!cat ? "border-accent text-accent" : "border-ink-600 text-fg-muted"}`} onClick={() => setCat(undefined)}>All ({items.length})</button>
          {cats.map((c) => (
            <button key={c} className={`chip ${cat === c ? "border-accent text-accent" : "border-ink-600 text-fg-muted"}`} onClick={() => setCat(c)}>
              {c} ({items.filter((d) => d.category === c).length})
            </button>
          ))}
        </div>
        {!shown.length && <Empty>No discoveries stored. Run the <code>discoveries</code> pipeline step after the mining modules.</Empty>}
        <div className="grid grid-cols-2 gap-3">
          {shown.map((d) => (
            <article key={d.discovery_id} id={d.discovery_id} className="panel p-4 flex flex-col">
              <div className="flex items-center justify-between gap-2">
                <span className="text-2xs uppercase tracking-wide text-fg-dim">{d.category}</span>
                <EvidenceChip kind={KIND[d.category] ?? "derived"} />
              </div>
              <h3 className="font-semibold mt-1 leading-snug">{d.title}</h3>
              <p className="text-sm text-fg-muted mt-1.5 leading-relaxed">{d.description}</p>
              <dl className="mt-3 grid grid-cols-2 gap-x-4 gap-y-1 text-2xs">
                <dt className="text-fg-dim">Algorithm</dt><dd>{d.algorithm} <span className="num text-fg-dim">({d.experiment_id})</span></dd>
                <dt className="text-fg-dim">Period</dt><dd>{d.period}</dd>
                <dt className="text-fg-dim">Extent</dt><dd className="num">{d.n_cells ? `${d.n_cells} cells (${fmt(d.n_cells * 0.25)} km²)` : "city-wide"}</dd>
                <dt className="text-fg-dim">Variables</dt><dd>{(d.variables ?? []).join(", ")}</dd>
                <dt className="text-fg-dim">Sources</dt><dd>{(d.sources ?? []).join(", ")}</dd>
                <dt className="text-fg-dim">Strength</dt><dd className="num">{fmt(d.strength, 2)}</dd>
              </dl>
              <details className="mt-2 text-2xs">
                <summary className="cursor-pointer text-fg-dim">Statistical evidence</summary>
                <pre className="mt-1 bg-ink-950 border border-ink-700 rounded p-2 overflow-x-auto scroll-thin">{JSON.stringify(d.evidence, null, 2)}</pre>
              </details>
              <div className="flex-1" />
              {d.lon != null && d.lat != null && (
                <button className="btn mt-3 self-start" onClick={() => {
                  setFlyTo({ lon: d.lon!, lat: d.lat!, zoom: d.zoom ?? 12 });
                  if (d.evidence?.example_cell) select(d.evidence.example_cell);
                  nav("/explore");
                }}>Show on map →</button>
              )}
            </article>
          ))}
        </div>
      </div>
    </div>
  );
}
